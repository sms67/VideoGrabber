def tr(lang: str, key: str, **kw) -> str:
    """Translate a key with fallback: requested lang -> en -> key itself."""
    s = STRINGS.get(lang, STRINGS["fa"]).get(key)
    if s is None:
        s = STRINGS["en"].get(key, key)
    if kw:
        try:
            return s.format(**kw)
        except Exception:
            return s
    return s
